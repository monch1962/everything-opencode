  /**
   * Generate language project
   */
  static generateLanguageProject(language, projectPath, variables = {}, options = {}) {
    const { overwrite = false, backup = true, createDir = true } = options;

    // Get language templates
    const templates = this.getLanguageTemplates(language);
    if (Object.keys(templates).length === 0) {
      throw new Error(`Unsupported language: ${language}`);
    }

    // Create project directory
    if (createDir && !fs.existsSync(projectPath)) {
      fs.mkdirSync(projectPath, { recursive: true });
    }

    const results = {
      generated: [],
      errors: [],
      total: Object.keys(templates).length,
    };

    // Generate each template file
    for (const [filename, template] of Object.entries(templates)) {
      const outputPath = path.join(projectPath, filename);

      try {
        const result = TemplateCore.generateFile(
          null, // No template file, use inline template
          outputPath,
          variables,
          { overwrite, backup, createDir: false }
        );

        // For inline templates, we need to write the content directly
        if (template) {
          const content = TemplateCore.renderTemplate(template, variables);
          fs.writeFileSync(outputPath, content, 'utf8');
        }

        results.generated.push({
          file: filename,
          path: outputPath,
          size: template ? template.length : 0,
        });
      } catch (error) {
        results.errors.push({
          file: filename,
          error: error.message,
        });
      }
    }

    return results;
  }

  /**
   * Generate language configuration
   */
  static generateLanguageConfig(language, configPath, variables = {}, options = {}) {
    const { overwrite = false, backup = true } = options;

    // Get default configuration for language
    const configs = {
      go: {
        'go.mod': `module {{module}}

go {{goVersion}}`,
      },
      python: {
        'pyproject.toml': `[project]
name = "{{name}}"
version = "{{version}}"
description = "{{description}}"
authors = [
    {name = "{{author}}"}
]

[build-system]
requires = ["setuptools"]
build-backend = "setuptools.build_meta"`,
      },
      node: {
        'package.json': `{
  "name": "{{name}}",
  "version": "{{version}}",
  "description": "{{description}}",
  "main": "index.js",
  "scripts": {
    "start": "node index.js",
    "test": "echo \\"Error: no test specified\\" && exit 1"
  },
  "keywords": [],
  "author": "{{author}}",
  "license": "{{license}}"
}`,
      },
      elixir: {
        'mix.exs': `defmodule {{module}}.MixProject do
  use Mix.Project

  def project do
    [
      app: :{{app}},
      version: "{{version}}",
      elixir: "{{elixirVersion}}",
      start_permanent: Mix.env() == :prod,
      deps: deps()
    ]
  end

  def application do
    [
      extra_applications: [:logger]
    ]
  end

  defp deps do
    []
  end
end`,
      },
    };

    const languageConfig = configs[language];
    if (!languageConfig) {
      throw new Error(`No configuration template for language: ${language}`);
    }

    const results = {
      generated: [],
      errors: [],
    };

    // Generate configuration files
    for (const [filename, template] of Object.entries(languageConfig)) {
      const outputPath = path.join(configPath, filename);

      try {
        const content = TemplateCore.renderTemplate(template, variables);

        // Check if file exists
        if (fs.existsSync(outputPath) && !overwrite) {
          throw new Error(`File already exists: ${outputPath}. Use overwrite option to replace.`);
        }

        // Backup existing file
        if (fs.existsSync(outputPath) && backup) {
          const backupPath = `${outputPath}.backup-${Date.now()}`;
          fs.copyFileSync(outputPath, backupPath);
        }

        // Write file
        fs.writeFileSync(outputPath, content, 'utf8');

        results.generated.push({
          file: filename,
          path: outputPath,
          size: content.length,
        });
      } catch (error) {
        results.errors.push({
          file: filename,
          error: error.message,
        });
      }
    }

    return results;
  }
